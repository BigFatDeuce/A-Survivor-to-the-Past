def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "..", "data", "lang")
    os.makedirs(root, exist_ok=True)
    full = list(KEYS)
    for w in WEAPONS:
        full += [f"weapon.{w}.name", f"weapon.{w}.desc"]
    for p in PASSIVES:
        full += [f"passive.{p}.name", f"passive.{p}.desc"]
    full.append("enemy.hinox")
    for code, table in L.items():
        missing = [k for k in full if k not in table]
        if missing:
            print(code, "manque :", missing)
        lines = [f"// Textes ({table['lang.name']}). Genere par research/tools/gen_lang.py, modifiable a la main.", "{"]
        for k in full:
            if k in table:
                lines.append(f'    "{k}": "{esc(table[k])}",')
        lines.append("}")
        with open(os.path.join(root, f"{code}.ron"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print("ecrit", code)


